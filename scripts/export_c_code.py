"""Generate C code for the ROS 2 package: the acados solver, the Panda dynamics (CasADi
code generation of the same expressions the Python package uses), and a header with the
constants (limits, ready pose, grid, circle, friction-model smoothing).

    python scripts/export_c_code.py [--out ros2/arm_nmpc_ros/generated]
"""

from __future__ import annotations

import argparse
import sys
import warnings
from pathlib import Path

import casadi as ca
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
warnings.filterwarnings("ignore")

from anmpc import dynamics as dy  # noqa: E402
from anmpc.nmpc import build_ocp, deploy_config  # noqa: E402
from anmpc.task import Q_READY, Circle, Friction, Limits  # noqa: E402


def arr(v):
    return "{" + ", ".join(f"{float(x):.17g}" for x in np.ravel(v)) + "}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "ros2" / "arm_nmpc_ros" / "generated"))
    out = Path(ap.parse_args().out).resolve()
    out.mkdir(parents=True, exist_ok=True)
    from acados_template import AcadosOcpSolver

    cfg = deploy_config(name="arm_nmpc")
    ocp = build_ocp(cfg)
    ocp.name = "arm_nmpc"
    ocp.code_export_directory = str(out / "c_generated_code")
    ocp.json_file = str(out / "c_generated_code" / "arm_nmpc.json")
    AcadosOcpSolver.generate(ocp, verbose=False)

    # Panda dynamics as plain C (CasADi code generation)
    q, dq, tau = ca.SX.sym("q", 7), ca.SX.sym("dq", 7), ca.SX.sym("tau", 7)
    p, _ = dy.fk_expr(q)
    funs = [
        ca.Function("panda_aba", [q, dq, tau], [dy.aba_expr(q, dq, tau)]),
        ca.Function("panda_fk", [q], [p]),
        ca.Function("panda_gravity", [q], [dy.rnea_expr(q, ca.SX.zeros(7), ca.SX.zeros(7))]),
    ]
    cg = ca.CodeGenerator("panda_dynamics.c", {"with_header": True})
    for f in funs:
        cg.add(f)
    cg.generate(str(out) + "/")

    lim, c, F = Limits(), Circle(1.0), Friction()
    hdr = f"""// generated by scripts/export_c_code.py - do not edit
#pragma once
namespace arm_nmpc {{
namespace params {{
constexpr int N = {cfg.N};
constexpr double time_steps[{cfg.N}] = {arr(cfg.time_steps)};
constexpr double q_ready[7] = {arr(Q_READY)};
constexpr double q_min[7] = {arr(lim.q_min)};
constexpr double q_max[7] = {arr(lim.q_max)};
constexpr double dq_max[7] = {arr(lim.dq_max)};
constexpr double tau_max[7] = {arr(lim.tau_max)};
constexpr double circle_center[3] = {arr(c.center)};
constexpr double circle_radius = {c.radius!r};
constexpr double circle_ramp = {c.ramp!r};
constexpr double sim_friction_fv[7] = {arr(F.fv)};
constexpr double sim_friction_fc[7] = {arr(F.fc)};
constexpr double sim_friction_eps = {F.eps!r};
}}  // namespace params
}}  // namespace arm_nmpc
"""
    (out / "arm_params.hpp").write_text(hdr)
    print(f"exported to {out}")


if __name__ == "__main__":
    main()
