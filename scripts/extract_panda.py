"""Extract the Franka Emika Panda's kinematic and inertial parameters into
src/anmpc/panda_data.py (7 arm joints; the fingers are locked and their mass merged).

    pip install pin example-robot-data
    python scripts/extract_panda.py

Source: panda.urdf from example-robot-data (BSD-3-Clause), based on franka_description
(Apache-2.0). Only numbers are copied; the package needs no URDF or Pinocchio at run
time (the tests use Pinocchio as the reference implementation).
"""

from __future__ import annotations

import glob
from pathlib import Path

import pinocchio as pin

ROOT = Path(__file__).resolve().parents[1]


def find_urdf():
    """panda.urdf of the pip package example-robot-data (installed under a cmeel prefix)."""
    import site
    import sys

    rel = "cmeel.prefix/share/example-robot-data/robots/panda_description/urdf/panda.urdf"
    roots = list(site.getsitepackages()) + [site.getusersitepackages(), sys.prefix]
    roots += [r.replace("site-packages", "dist-packages") for r in roots]
    for r in roots:
        p = Path(r) / rel
        if p.exists():
            return str(p)
    for r in roots:  # bounded search, one level of nesting
        hits = glob.glob(str(Path(r) / "*" / rel))
        if hits:
            return hits[0]
    raise SystemExit("panda.urdf not found: pip install example-robot-data")


def reduced_model():
    full = pin.buildModelFromUrdf(find_urdf())
    lock = [full.getJointId("panda_finger_joint1"), full.getJointId("panda_finger_joint2")]
    m = pin.buildReducedModel(full, lock, pin.neutral(full))
    assert m.nq == 7
    return m


def main():
    m = reduced_model()
    f = m.frames[m.getFrameId("panda_hand_tcp")]
    assert f.parentJoint == 7

    def L(a):
        return repr(a.round(12).tolist())

    lines = [
        '"""Franka Emika Panda parameters (generated by scripts/extract_panda.py).',
        "",
        "From panda.urdf in example-robot-data (BSD-3-Clause), based on franka_description",
        "(Apache-2.0). Fingers locked at 0, their mass merged into link 7. All joints",
        'revolute about their local z axis."""',
        "import numpy as np",
        "",
        "# placement of joint i in its parent's frame: rotation R (3x3), translation p",
        "JOINT_R = np.array("
        + repr([m.jointPlacements[i].rotation.round(12).tolist() for i in range(1, 8)])
        + ")",
        "JOINT_P = np.array("
        + repr([m.jointPlacements[i].translation.round(12).tolist() for i in range(1, 8)])
        + ")",
        "# link inertia in the joint frame: mass, centre of mass, rotational inertia at the CoM",
        "MASS = np.array(" + repr([float(m.inertias[i].mass) for i in range(1, 8)]) + ")",
        "COM = np.array("
        + repr([m.inertias[i].lever.round(12).tolist() for i in range(1, 8)])
        + ")",
        "I_COM = np.array("
        + repr([m.inertias[i].inertia.round(12).tolist() for i in range(1, 8)])
        + ")",
        "# tool centre point in the frame of joint 7",
        "TCP_R = np.array(" + L(f.placement.rotation) + ")",
        "TCP_P = np.array(" + L(f.placement.translation) + ")",
        "Q_MIN = np.array(" + L(m.lowerPositionLimit) + ")",
        "Q_MAX = np.array(" + L(m.upperPositionLimit) + ")",
        "DQ_MAX = np.array(" + L(m.velocityLimit) + ")",
        "TAU_MAX = np.array(" + L(m.effortLimit) + ")",
        "GRAVITY = np.array(" + repr(m.gravity.linear.tolist()) + ")",
        "",
    ]
    out = ROOT / "src" / "anmpc" / "panda_data.py"
    out.write_text("\n".join(lines))
    print("wrote", out)


if __name__ == "__main__":
    main()
